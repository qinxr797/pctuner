function Get-TweakGameVerdict {
    <#
      取某个优化项对某个场景的结论。

      取不到时的兜底：以前不管什么场景都返回一句
      「对这个游戏没有直接影响」—— 对「不玩游戏」的人来说
      这句话本身就是错的（他根本没有"这个游戏"）。
      所以兜底文案也按场景分。
    #>
    param([hashtable]$Notes, [string]$TweakId, [string]$GameKey)
    if ($Notes.ContainsKey($TweakId) -and $Notes[$TweakId].ContainsKey($GameKey)) {
        return $Notes[$TweakId][$GameKey]
    }
    $fallback = switch ($GameKey) {
        'OFFICE' { '对日常办公上网没有直接影响，属于系统层面的通用整理。' }
        'OLD'    { '对老机器没有特别的影响，属于系统层面的通用整理。' }
        default  { '对这类游戏没有直接影响，属于系统层面的通用整理。' }
    }
    return @{ V = '中性'; N = $fallback }
}

function Get-MergedVerdicts {
    <#
      把八个场景的结论按「结论 + 理由都相同」合并成若干组。

      ★ 为什么要合并 ★
        八个场景全平铺的话，每个优化项下面要堆八张卡片，
        而其中大半是一模一样的内容（比如「关鼠标加速」对
        大型单机 / 网游 / 轻度游戏 说的其实是同一件事）。
        合并之后通常剩 2~4 张，信息一条不少，但读得动。

      返回 @( @{ Names=@('大型单机','网游挂机'); V='推荐'; N='...' } , ... )
      保持 GAME_LIST 的原始顺序，不打乱。
    #>
    param([hashtable]$Notes, [string]$TweakId)

    $groups = New-Object System.Collections.ArrayList
    foreach ($g in $Script:GAME_LIST) {
        $v = Get-TweakGameVerdict -Notes $Notes -TweakId $TweakId -GameKey $g.Key

        # 和上一组比：结论和理由都一样就并进去，否则另起一组。
        # 只跟「上一组」比而不是跟所有组比，是为了保持原顺序 ——
        # 否则 CS2 和最后一个场景相同的话会被拉到一起，读起来很怪。
        $last = if ($groups.Count -gt 0) { $groups[$groups.Count - 1] } else { $null }
        if ($null -ne $last -and $last.V -eq $v.V -and $last.N -eq $v.N) {
            [void]$last.Names.Add($g.Short)
        } else {
            $names = New-Object System.Collections.ArrayList
            [void]$names.Add($g.Short)
            [void]$groups.Add([PSCustomObject]@{ Names = $names; V = $v.V; N = $v.N })
        }
    }
    return $groups
}

function Get-SelectionWarnings {
    <#
      兼容性检查：给一组勾选的优化项，找出「可能让某个游戏吃亏」的地方。
      这是为了兑现「不能因为照顾一个游戏而牺牲另外两个」这条要求。
    #>
    param([string[]]$TweakIds)
    $notes = Get-GameNotes
    $warn = @()

    foreach ($id in $TweakIds) {
        foreach ($g in $Script:GAME_LIST) {
            $v = Get-TweakGameVerdict -Notes $notes -TweakId $id -GameKey $g.Key
            if ($v.V -eq '慎用') {
                $warn += ("「{0}」对《{1}》可能不利：{2}" -f $id, $g.Short, $v.N)
            }
        }
    }

    # 专门针对国际服 Valorant 的提醒（唯一一个方向相反的情况）
    if (($TweakIds -contains 'VBS') -or ($TweakIds -contains 'HyperV')) {
        $warn += '提示：你勾了「关闭内核隔离 / Hyper-V」。这是无畏契约国服和三角洲行动的启动硬性要求，CS2 也受益。但【国际服】Valorant（Vanguard 反作弊）的要求正好相反，如果以后要玩国际服，把这两项单独还原即可。'
    }
    return $warn
}
