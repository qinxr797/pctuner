<#
=====================================================================
  Games.ps1  ——  FPS 游戏适配层
---------------------------------------------------------------------
  这个文件回答两个问题：

    1) 每一个优化项，对 CS2 / 无畏契约 / 三角洲行动 分别意味着什么？
    2) 三个游戏都要玩的话，该勾哪些？（预设）

  ★ 最重要的一条结论（查证过官方资料）★

    无畏契约「国服」和三角洲行动，用的都是腾讯 ACE 反作弊。
    ACE 需要独占 CPU 虚拟化来对抗 DMA 外挂，所以它要求：
        · BIOS 里：VT-x / VT-d（AMD 叫 SVM / IOMMU）要【开】
        · Windows 里：内存完整性(HVCI)、VBS、Hyper-V 要【关】
    这不是性能优化，是「不关就弹窗、进不去游戏」的硬性要求。
    ——来源：腾讯游戏安全中心 gamesafe.qq.com/article/1181.shtml

    而 CS2 用的是 VAC，对这些完全不管；并且第三方实测显示
    关掉内核隔离(VBS) 能让 CS2 多出约 25 帧。

    所以：关闭 VBS / Hyper-V 这一组操作，
          对这三个游戏【全部是正收益】，其中两个还是硬性要求。
          不存在「为了一个牺牲另外两个」的情况。

  ★ 唯一需要注意的例外 ★

    如果哪天去玩【国际服】Valorant（用的是 Riot 自己的 Vanguard，
    不是 ACE），Vanguard 的要求正好【相反】—— 它要求内存完整性
    开着，关了会报 "VAN: RESTRICTION - HVCI"。
    真要切国际服，把「关闭内核隔离」这一项还原回去即可。
    界面上这一项会专门标出来。
